def set_default_font(doc, name="Times New Roman", size=14):
    style = doc.styles["Normal"]
    style.font.name = name
    style.font.size = Pt(size)
    rpr = style.element.get_or_add_rPr()
    rFonts = rpr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = OxmlElement("w:rFonts")
        rpr.insert(0, rFonts)
    rFonts.set(qn("w:eastAsia"), name)
    rFonts.set(qn("w:cs"), name)
    rFonts.set(qn("w:ascii"), name)
    rFonts.set(qn("w:hAnsi"), name)


def p(doc, text, *, bold=False, italic=False, size=14, align=None, indent=1.25):
    para = doc.add_paragraph()
    para.paragraph_format.first_line_indent = Cm(indent) if indent else None
    para.paragraph_format.line_spacing = 1.5
    para.paragraph_format.space_after = Pt(0)
    if align is not None:
        para.alignment = align
    r = para.add_run(text)
    r.bold = bold
    r.italic = italic
    r.font.size = Pt(size)
    r.font.name = "Times New Roman"
    return para


def h(doc, text, level=1):
    sizes = {1: 16, 2: 14, 3: 13}
    para = doc.add_paragraph()
    para.paragraph_format.space_before = Pt(12)
    para.paragraph_format.space_after = Pt(6)
    para.paragraph_format.line_spacing = 1.5
    if level == 1:
        para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = para.add_run(text.upper() if level == 1 else text)
    r.bold = True
    r.font.size = Pt(sizes.get(level, 14))
    r.font.name = "Times New Roman"
    return para


def bullet(doc, text):
    para = doc.add_paragraph(style="List Bullet")
    para.paragraph_format.line_spacing = 1.5
    para.paragraph_format.space_after = Pt(0)
    r = para.runs[0] if para.runs else para.add_run("")
    r.text = text
    r.font.size = Pt(14)
    r.font.name = "Times New Roman"


